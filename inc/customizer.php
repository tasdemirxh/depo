/**
 * Sanitize checkbox settings.
 *
 * @param mixed $checked Raw checkbox value.
 * @return bool
 */
function novashop_sanitize_checkbox( $checked ) {
	return (bool) $checked;
}

/**
 * Sanitize URL-like settings while allowing section anchors.
 *
 * @param string $url Raw URL.
 * @return string
 */
function novashop_sanitize_link( $url ) {
	$url = trim( $url );

	if ( 0 === strpos( $url, '#' ) ) {
		return sanitize_text_field( $url );
	}

	return esc_url_raw( $url );
}

/**
 * Register theme customizer options.
 *
 * @param WP_Customize_Manager $wp_customize Customizer object.
 * @return void
 */
function novashop_customize_register( $wp_customize ) {
	$defaults = novashop_option_defaults();

	$wp_customize->add_section( 'novashop_branding', array(
		'title'       => __( 'NovaShop branding', 'novashop' ),
		'description' => __( 'Control the main storefront colors and header messaging.', 'novashop' ),
		'priority'    => 30,
	) );

	$wp_customize->add_setting( 'accent_color', array(
		'default'           => $defaults['accent_color'],
		'sanitize_callback' => 'sanitize_hex_color',
		'transport'         => 'refresh',
	) );

	$wp_customize->add_control( new WP_Customize_Color_Control(
		$wp_customize,
		'accent_color',
		array(
			'label'   => __( 'Accent color', 'novashop' ),
			'section' => 'novashop_branding',
		)
	) );

	$wp_customize->add_setting( 'header_topline', array(
		'default'           => $defaults['header_topline'],
		'sanitize_callback' => 'sanitize_text_field',
	) );

	$wp_customize->add_control( 'header_topline', array(
		'label'   => __( 'Top bar message', 'novashop' ),
		'section' => 'novashop_branding',
		'type'    => 'text',
	) );

	$wp_customize->add_setting( 'sticky_header', array(
		'default'           => $defaults['sticky_header'],
		'sanitize_callback' => 'novashop_sanitize_checkbox',
	) );

	$wp_customize->add_control( 'sticky_header', array(
		'label'   => __( 'Enable sticky header', 'novashop' ),
		'section' => 'novashop_branding',
		'type'    => 'checkbox',
	) );

	$wp_customize->add_section( 'novashop_hero', array(
		'title'       => __( 'Homepage hero', 'novashop' ),
		'description' => __( 'Edit the primary conversion area shown on the front page.', 'novashop' ),
		'priority'    => 35,
	) );

	$hero_fields = array(
		'hero_badge'           => array( __( 'Badge text', 'novashop' ), 'text', 'sanitize_text_field' ),
		'hero_title'           => array( __( 'Title', 'novashop' ), 'text', 'sanitize_text_field' ),
		'hero_text'            => array( __( 'Description', 'novashop' ), 'textarea', 'sanitize_textarea_field' ),
		'hero_primary_label'   => array( __( 'Primary button label', 'novashop' ), 'text', 'sanitize_text_field' ),
		'hero_primary_link'    => array( __( 'Primary button link', 'novashop' ), 'url', 'novashop_sanitize_link' ),
		'hero_secondary_label' => array( __( 'Secondary button label', 'novashop' ), 'text', 'sanitize_text_field' ),
		'hero_secondary_link'  => array( __( 'Secondary button link', 'novashop' ), 'url', 'novashop_sanitize_link' ),
	);

	foreach ( $hero_fields as $field => $config ) {
		$wp_customize->add_setting( $field, array(
			'default'           => $defaults[ $field ],
			'sanitize_callback' => $config[2],
		) );

		$wp_customize->add_control( $field, array(
			'label'   => $config[0],
			'section' => 'novashop_hero',
			'type'    => $config[1],
		) );
	}

	$wp_customize->add_section( 'novashop_footer', array(
		'title'    => __( 'Footer', 'novashop' ),
		'priority' => 40,
	) );

	$wp_customize->add_setting( 'footer_text', array(
		'default'           => $defaults['footer_text'],
		'sanitize_callback' => 'sanitize_text_field',
	) );

	$wp_customize->add_control( 'footer_text', array(
		'label'   => __( 'Footer bottom text', 'novashop' ),
		'section' => 'novashop_footer',
		'type'    => 'text',
	) );
}
add_action( 'customize_register', 'novashop_customize_register' );

/**
 * Print dynamic CSS variables generated by Customizer options.
 *
 * @return void
 */
function novashop_customizer_css() {
	$accent = sanitize_hex_color( novashop_get_option( 'accent_color' ) );

	if ( ! $accent ) {
		$accent = '#7a4bff';
	}
	?>
	<style id="novashop-customizer-css">
		:root {
			--novashop-accent: <?php echo esc_html( $accent ); ?>;
		}
	</style>
	<?php
}
add_action( 'wp_head', 'novashop_customizer_css' );
